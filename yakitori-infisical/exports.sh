# Sourced by Umbrel before rendering templates and starting Compose.
# Each secret has its own derivation label; none is reused for another purpose.

export APP_INFISICAL_POSTGRES_PASSWORD="$(derive_entropy "${app_entropy_identifier}-postgres-password")"
export APP_INFISICAL_AUTH_SECRET="$(derive_entropy "${app_entropy_identifier}-auth-secret")"

# Infisical's InstanceEncryptionKey requires ENCRYPTION_KEY (UTF-8) to decode
# to 32 bytes (32 hex chars = 128-bit entropy), whereas ROOT_ENCRYPTION_KEY
# decodes base64 to 32 raw bytes (full 256-bit entropy). Convert the 64-hex
# output of derive_entropy into standard base64 using only POSIX awk/printf/base64.
# Note: InstanceEncryptionKey.fromEnv() checks `env.ENCRYPTION_KEY || env.ROOT_ENCRYPTION_KEY`,
# so setting ENCRYPTION_KEY in Umbrel App Settings cleanly promotes a 32-hex key
# generated by Infisical's Admin Console rotation UI without removing ROOT_ENCRYPTION_KEY.
APP_INFISICAL_ROOT_KEY_HEX="$(derive_entropy "${app_entropy_identifier}-root-encryption-key")"
APP_INFISICAL_ROOT_KEY_OCT="$(awk -v h="${APP_INFISICAL_ROOT_KEY_HEX}" 'BEGIN {
  for (i = 1; i <= length(h); i += 2) {
    hi = index("0123456789abcdef", tolower(substr(h, i, 1))) - 1
    lo = index("0123456789abcdef", tolower(substr(h, i + 1, 1))) - 1
    printf "\\0%03o", hi * 16 + lo
  }
}')"
export APP_INFISICAL_ROOT_ENCRYPTION_KEY="$(printf '%b' "${APP_INFISICAL_ROOT_KEY_OCT}" | base64 | tr -d '\n')"
unset APP_INFISICAL_ROOT_KEY_HEX APP_INFISICAL_ROOT_KEY_OCT

# APP_PROXY_PORT is assigned after exports.sh is sourced by Umbrel, so retain
# the manifest's port as a fallback. DEVICE_DOMAIN_NAME is already available.
PORT="${APP_PROXY_PORT:-8311}"
LOCAL_DOMAIN="${DEVICE_DOMAIN_NAME:-umbrel.local}"
export APP_INFISICAL_SITE_URL="https://${LOCAL_DOMAIN}:${PORT}"

# Never let TRUSTED_PROXY_CIDRS expand to a malformed "/16" when NETWORK_IP is unset.
# Note: on umbrelOS 2.0, HTTPS LAN ingress reaches AppGateway over 127.0.0.1,
# so AppGateway forwards X-Forwarded-For: 127.0.0.1 from the Docker bridge gateway.
export APP_INFISICAL_TRUSTED_PROXIES="${NETWORK_IP:-10.21.0.0}/16"
